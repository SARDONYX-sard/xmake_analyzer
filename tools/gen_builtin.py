#!/usr/bin/env python3
"""Generates crates/xmake_api/src/generated.rs from the installed xmake.

Usage: python tools/gen_builtin.py [--xmake PATH]

The language server also reads these lists from the xmake found at runtime;
the generated tables are the fallback when xmake is missing, and the source of
the API kinds (values, paths, script, ...) that `xmake show` does not print.
"""

import argparse
import json
import os
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "crates" / "xmake_api" / "src" / "generated.rs"

SCOPES = ["root", "target", "option", "rule", "package", "toolchain", "task"]
SCOPE_VARIANT = {s: s.capitalize() for s in SCOPES}
KIND_VARIANT = {
    "values": "Values",
    "paths": "Paths",
    "keyvalues": "KeyValues",
    "dictionary": "Dictionary",
    "groups": "Groups",
    "script": "Script",
    "custom": "Custom",
}

# Registered by the interpreter itself, not listed by `xmake show`.
EXTRA_DESCRIPTION_FUNCTIONS = ["add_subdirs", "add_subfiles", "namespace", "namespace_end"]

# `core.base.task` cannot be imported from `xmake l`.
TASK_APIS = {"values": ["set_category"], "dictionary": ["set_menu"], "script": ["on_run"]}


def run_xmake(xmake, args, cwd):
    env = dict(os.environ, COLORTERM="nocolor", XMAKE_THEME="plain")
    out = subprocess.run([xmake, *args], cwd=cwd, env=env, capture_output=True, text=True, timeout=300)
    out.check_returncode()
    # Skip anything printed before the JSON document.
    text = out.stdout
    start = min(i for i in (text.find("{"), text.find("[")) if i >= 0)
    return json.loads(text[start:])


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def str_list(items, indent="    "):
    if not items:
        return "&[]"
    body = "".join(f"{indent}    B({rust_str(i)}),\n" for i in items)
    return f"&[\n{body}{indent}]"


def modules(names):
    """Groups `os.cp` style names by module."""
    grouped = {}
    for full in names:
        module, _, func = full.rpartition(".")
        if module:
            grouped.setdefault(module, []).append(func)
    return {m: sorted(set(f)) for m, f in sorted(grouped.items())}


def module_list(names):
    out = []
    for module, funcs in modules(names).items():
        out.append(
            f"    Module {{ name: B({rust_str(module)}), functions: B({str_list(funcs, '        ')}) }},\n"
        )
    return "&[\n" + "".join(out) + "]"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--xmake", default="xmake")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as cwd:
        scopes = run_xmake(args.xmake, ["l", str(ROOT / "tools" / "dump_scopes.lua")], cwd)
        apis = run_xmake(args.xmake, ["show", "-l", "apis", "--json"], cwd)
        lists = {
            name: run_xmake(args.xmake, ["show", "-l", name, "--json"], cwd)
            for name in ["platforms", "architectures", "buildmodes", "rules", "policies", "toolchains"]
        }

    # (scope, name) -> kind. `language.apis()` adds flags to several scopes.
    scope_apis = {}
    raw_scopes = dict(scopes["scopes"])
    raw_scopes["task"] = {k: [f"task.{n}" for n in v] for k, v in TASK_APIS.items()}
    for owner, kinds in raw_scopes.items():
        for kind, names in kinds.items():
            for full in names:
                scope, _, name = full.rpartition(".")
                scope = scope or "root"
                if owner == "root" or scope == "":
                    scope = "root"
                scope_apis[(scope, name)] = kind
    # Names `xmake show` knows but the dump missed: infer the kind.
    for full in apis.get("description_scope_apis", []):
        scope, _, name = full.rpartition(".")
        if scope in SCOPES:
            scope_apis.setdefault((scope, name), "script" if name.split("_")[0] in ("on", "before", "after") else "values")

    root_names = {n for (s, n) in scope_apis if s == "root"}
    description_functions = sorted(
        (set(apis["description_builtin_apis"]) | set(EXTRA_DESCRIPTION_FUNCTIONS)) - root_names
    )

    instances = {}
    for full in apis["script_instance_apis"]:
        inst, _, method = full.partition(":")
        instances.setdefault(inst, set()).add(method)

    archs = sorted({a for v in lists["architectures"].values() for a in v})

    out = []
    w = out.append
    w(f"//! Generated by `tools/gen_builtin.py` from xmake {scopes['version']}. Do not edit.\n\n")
    w("use std::borrow::Cow::Borrowed as B;\n\n")
    w("use crate::{ApiKind as K, Instance, InstanceMethods, Module, Named, Scope as S, ScopeApi, Str};\n\n")
    w(f"pub(crate) const VERSION: &str = {rust_str(scopes['version'])};\n\n")

    w("pub(crate) static SCOPE_APIS: &[ScopeApi] = &[\n")
    order = {s: i for i, s in enumerate(SCOPES)}
    for (scope, name), kind in sorted(scope_apis.items(), key=lambda x: (order[x[0][0]], x[0][1])):
        w(f"    ScopeApi {{ scope: S::{SCOPE_VARIANT[scope]}, name: B({rust_str(name)}), kind: K::{KIND_VARIANT[kind]} }},\n")
    w("];\n\n")

    w(f"pub(crate) static DESCRIPTION_FUNCTIONS: &[Str] = {str_list(description_functions, '')};\n\n")
    w(f"pub(crate) static DESCRIPTION_MODULES: &[Module] = {module_list(apis['description_builtin_module_apis'])};\n\n")
    w(f"pub(crate) static SCRIPT_FUNCTIONS: &[Str] = {str_list(sorted(set(apis['script_builtin_apis'])), '')};\n\n")
    w(f"pub(crate) static SCRIPT_MODULES: &[Module] = {module_list(apis['script_builtin_module_apis'])};\n\n")

    w("pub(crate) static INSTANCE_METHODS: &[InstanceMethods] = &[\n")
    for inst in sorted(instances):
        w(f"    InstanceMethods {{ instance: Instance::{inst.capitalize()}, methods: B({str_list(sorted(instances[inst]), '        ')}) }},\n")
    w("];\n\n")

    w(f"pub(crate) static EXTENSION_APIS: &[Str] = {str_list(sorted(set(apis['script_extension_module_apis'])), '')};\n\n")

    w(f"pub(crate) static PLATFORMS: &[Str] = {str_list(sorted(lists['platforms']), '')};\n\n")
    w(f"pub(crate) static ARCHITECTURES: &[Str] = {str_list(archs, '')};\n\n")
    w(f"pub(crate) static MODES: &[Str] = {str_list(sorted(lists['buildmodes']), '')};\n\n")
    w(f"pub(crate) static RULES: &[Str] = {str_list(sorted(lists['rules']), '')};\n\n")
    for name, key in [("POLICIES", "policies"), ("TOOLCHAINS", "toolchains")]:
        w(f"pub(crate) static {name}: &[Named] = &[\n")
        for item in sorted(lists[key], key=lambda x: x["name"]):
            desc = item.get("description") or ""
            w(f"    Named {{ name: B({rust_str(item['name'])}), description: B({rust_str(desc)}) }},\n")
        w("];\n")
        if name == "POLICIES":
            w("\n")

    OUT.write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(scope_apis)} scope apis")


if __name__ == "__main__":
    main()
